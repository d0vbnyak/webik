/**
 * Какие заказы интересны WebIK. Студия делает редизайн старых сайтов, лендинги
 * под ключ, чат-боты, голосовых роботов и ИИ-автоматизацию (docs/прайс.md,
 * shared/prices.json) — заказ проходит, если в заголовке или описании есть
 * одна из этих тем и нет стоп-слов.
 *
 * Темы ищутся в заголовке. В описании — только у тем с descriptionToo:
 * «ИИ», «бот» и «автоматизация» в описаниях встречаются мимоходом
 * («фото с AI-генерацией», «не ИИ»), а редизайн часто описан только там.
 *
 * \b в JS не знает кириллицу, поэтому границы слова — через (?<![а-яё]).
 */

export type Topic = { name: string; patterns: RegExp[]; descriptionToo?: boolean };

const W = "(?<![а-яёa-z0-9])"; // начало слова
const E = "(?![а-яёa-z0-9])"; // конец слова
const re = (s: string) => new RegExp(s, "iu");

export const TOPICS: Topic[] = [
  {
    name: "Редизайн",
    descriptionToo: true,
    patterns: [
      re("редизайн"),
      re("(передел|обнов|осовремен|модерниз|переверста|переписа)\\S*\\s+(\\S+\\s+){0,2}сайт"),
      re("сайт\\S*\\s+(\\S+\\s+){0,2}(передел|обнов|осовремен|модерниз)"),
      re("(стар|устарев)\\S*\\s+сайт"),
      re("(перенос|перенест|миграц)\\S*\\s+(\\S+\\s+){0,2}сайт\\S*\\s+(с|на)\\s"),
    ],
  },
  {
    name: "Сайт / лендинг",
    patterns: [
      re("лендинг"),
      re(`${W}landing`),
      re("одностранич"),
      re("сайт\\S*[-\\s]визитк"),
      re("(сделать|создать|создание|разработ\\S*|нуж\\S*|сверстать|верстк\\S*)\\s+(\\S+\\s+){0,2}сайт"),
      re("сайт\\S*\\s+под\\s+ключ"),
      re(`${W}astro${E}`),
    ],
  },
  {
    name: "Чат-бот",
    patterns: [
      re("чат[-\\s]?бот"),
      re(`${W}бот(а|ы|ов|ом|у|е)?${E}`),
      re("telegram[-\\s]?bot"),
      re(`${W}bot${E}`),
    ],
  },
  {
    name: "ИИ",
    patterns: [
      re("нейросет"),
      re("нейронн"),
      re("искусственн\\S*\\s+интеллект"),
      re(`${W}ии${E}`),
      re(`${W}ии-`),
      re(`${W}ai${E}`),
      re(`${W}ai-`),
      re(`${W}(chat)?gpt`),
      re(`${W}llm`),
      re(`${W}rag${E}`),
      re("deepseek|yandexgpt|gigachat|claude|openai|qwen"),
      re("ии[-\\s]?(агент|ассистент)|ai[-\\s]?(агент|agent|ассистент)"),
    ],
  },
  {
    name: "Автоматизация",
    patterns: [
      re("автоматизац"),
      re(`${W}n8n${E}`),
      re("make\\.com"),
      re("интеграц\\S*\\s+(\\S+\\s+){0,2}(crm|црм|амо|amo|битрикс|1с|1c)"),
      re(`${W}ocr${E}`),
      re("распознав\\S*\\s+(документ|чек|счет|счёт|накладн|текст)"),
      re("голосов\\S*\\s+(робот|бот|ассистент|помощник)"),
      re("(авто)?обзвон"),
    ],
  },
];

/**
 * Стоп-слова — проверяются только в заголовке: в описании они часто
 * встречаются мимоходом («отзывы клиентов на сайте»).
 */
export const STOP_PATTERNS: RegExp[] = [
  re("ваканси"),
  re("в\\s+штат"),
  re("на\\s+постоянн\\S*\\s+основ"),
  re("накрут"),
  re("(курсов|дипломн|контрольн)\\S*\\s+работ"),
  re("реферат"),
  re(`${W}smm${E}`),
  re("логотип"),
  re("наполнени\\S*\\s+(сайт|карточ|магазин)"),
  re("парсинг\\s+(отзыв|wildberries|ozon)"),
  // ИИ для картинок, видео и текстов — не услуга студии
  re("не\\s+(ии|ai|нейросет)"),
  re(`${W}(ai|ии|нейро\\S*)[-\\s]+(\\S+\\s+){0,2}(фото|видео|клип|аватар|картин|изображ)`),
  re(`(фото|видео|клип|аватар|картин|изображ)\\S*\\s+(\\S+\\s+){0,3}(ai|ии|нейросет)${E}`),
  re("видеоклип|монтаж|reels"),
  // AI — ещё и формат Illustrator: «векторные файлы (CDR/AI)»
  re("вектор|айдентик|фирменн\\S*\\s+стил|(cdr|eps|svg|pdf)\\s*/\\s*ai"),
  re("(генерац|сгенерир)\\S*\\s+(\\S+\\s+){0,2}(фото|текст|стат|музык)"),
  re("копирайт|рерайт|статей|статьи|презентаци\\S*\\s+в\\s+power\\s*point|оформлени\\S*\\s+презентац"),
  // SEO и продвижение сняты с продажи: «Нужен SEO для сайта» — не заказ на сайт
  re("^(нуж\\S*\\s+)?(seo|сео|продвижени)"),
  re(`${W}(3d|3д)`),
  re("песн|музык|озвуч"),
  re("наставник|обучени\\S*\\s+(\\S+\\s+){0,2}(нейросет|ии|ai)|ищу\\s+(предпринимат|тестиров|респондент)"),
];

export type Match = { topics: string[] };

export type FilterOptions = { minBudget: number };

/** Почему заказ интересен (список тем) или null — не интересен. */
export function matchJob(job: { title: string; description: string; budgetRub: number | null }, opts: FilterOptions): Match | null {
  if (STOP_PATTERNS.some((p) => p.test(job.title))) return null;
  // Без бюджета — пропускаем: «по договорённости» бывает у самых крупных заказов
  if (job.budgetRub !== null && job.budgetRub < opts.minBudget) return null;

  const topics = TOPICS.filter((t) =>
    t.patterns.some((p) => p.test(job.title) || (t.descriptionToo === true && p.test(job.description))),
  ).map((t) => t.name);
  return topics.length ? { topics } : null;
}
